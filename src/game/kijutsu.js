// 文章の中の添付書類（かっこの中＝「〜は不要」などの補足は数えない）
export function docsIn(text) {
  let t = String(text || "").replace(/（[^）]*）/g, " ").replace(/\([^)]*\)/g, " ");
  const found = [];
  [...DOC_LIST].sort((a, b) => b.length - a.length).forEach((d) => {
    if (t.includes(d)) { found.push(d); t = t.split(d).join(" "); }
  });
  return DOC_LIST.filter((d) => found.includes(d));
}
// 1件の申請か（①②・1件目・第1欄などで分かれていないか）
export function isSingleApp(text) {
  return !/[①②③④]|件目|第\d欄|問\d|甲地＝|乙地＝/.test(String(text || ""));
}

const secOf = (y, h) => (y.secs || []).find((s) => s.h === h);
const linesOf = (sec) => (sec ? sec.items.filter((i) => i.p).map((i) => i.p) : []);
function rowOf(y, h, key) {
  const s = secOf(y, h);
  if (!s) return null;
  for (const it of s.items) {
    if (!it.tbl) continue;
    for (const r of it.tbl) if (r[0] && r[0].join(" ").startsWith(key)) return r.slice(1).map((c) => c.join("\n")).join("\n");
  }
  return null;
}
function tableRows(y, h) {
  const s = secOf(y, h);
  if (!s) return [];
  const out = [];
  s.items.forEach((it) => { if (it.tbl) it.tbl.slice(1).forEach((r) => out.push(r.map((c) => c.join("\n")))); else if (it.p) out.push([it.p]); });
  return out;
}

// 「自分で決めること」ごとの模範解答
export function modelAnswers(y) {
  const pur = secOf(y, "登記の目的");
  const purLines = linesOf(pur);
  const purMain = purLines.filter((l) => /登記|^[①②③④]|^【|^（/.test(l) && l.length < 80 && !l.replace(/（[^）]*）/g, "").includes("。"));
  const purpose = (purMain.length ? purMain : purLines.slice(0, 1)).join("\n");
  const why = purLines.filter((l) => !purMain.includes(l)).join("\n");
  const m = {};
  if (y.kind === "land") {
    m["登記の目的"] = purpose;
    m["申請の件数"] = pur && pur.note ? pur.note : (purMain.length > 1 ? `${purMain.length}件` : "1件");
    m["申請人"] = rowOf(y, "申請書の骨格", "申請人");
    m["原因及びその日付・冠記"] = [rowOf(y, "申請書の骨格", "原因及びその日付"), ...tableRows(y, "土地の表示欄").map((r) => r.join("：")).filter(Boolean)].filter(Boolean).join("\n");
    m["添付書類"] = rowOf(y, "申請書の骨格", "添付書類");
    m["地積更正の要否"] = linesOf(secOf(y, "地積更正の要否")).join("\n");
    m["登録免許税"] = rowOf(y, "申請書の骨格", "登録免許税");
  } else {
    m["登記の目的"] = purpose;
    m["原因及びその日付"] = linesOf(secOf(y, "原因及びその日付")).join("\n");
    m["床面積（測定基準）"] = linesOf(secOf(y, "床面積 ― 測定基準と算入・不算入")).join("\n");
    m["床面積（答え）"] = floorRows(y).map((r) => `${r.label}　${r.ans}`).join("\n");
    m["添付書類"] = rowOf(y, "申請書の要点", "添付書類");
  }
  return { m, why };
}
// 答案の欄（決めることの並び。データの decide がなければ既定）
export function decideOf(y) {
  if (y.decide && y.decide.length) return y.decide;
  return y.kind === "land" ? ["登記の目的", "申請の件数", "申請人", "原因及びその日付・冠記", "添付書類", "地積更正の要否", "登録免許税"] : ["登記の目的", "原因及びその日付", "床面積（測定基準）", "床面積（答え）", "添付書類"];
}

// 建物の床面積の求積（区分ごとの式と答え）
export function floorRows(y) {
  const s = secOf(y, "床面積 ― 求積");
  if (!s) return [];
  const out = [];
  s.items.forEach((it) => {
    if (!it.tbl) return;
    it.tbl.slice(1).forEach((r) => {
      if (r.length < 3) return;
      const label = r[0].join(" ");
      const lines = r[1];
      const ans = r[2].join(" ");
      const nums = ans.match(/\d+\.\d+/g) || [];
      out.push({ label, lines, ans, v: nums.length === 1 ? parseFloat(nums[0]) : null });
    });
  });
  return out;
}
export function floorKeys(y) {
  const s = secOf(y, "電卓のキー操作");
  if (!s) return [];
  return s.items.flatMap((it) => it.keys || []);
}
// 式の答えを隠す（「6.37 × 8.19 ＝ 52.1703」→「6.37 × 8.19 ＝ ？」、「計」の行は出さない）
export function hideResult(line) {
  if (/^計\s/.test(line.trim())) return null;
  return line.replace(/＝\s*[\d.]+/g, "＝ ？");
}

