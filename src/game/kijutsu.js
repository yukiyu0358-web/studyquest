const BASE = (import.meta.env && import.meta.env.BASE_URL) || "/";
const cache = new Map();
export function loadData(name) {
  if (!cache.has(name)) cache.set(name, fetch(`${BASE}data/${name}.json`).then((r) => (r.ok ? r.json() : null)).catch(() => null));
  return cache.get(name);
}

